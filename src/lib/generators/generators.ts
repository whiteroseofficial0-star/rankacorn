import { escapeXml } from "../seo/sitemap.ts";

const attr = escapeXml;

/** Make JSON safe to embed inside a <script> tag. */
const safeJson = (o: unknown) => JSON.stringify(o, null, 2).replace(/</g, "\\u003c");

export function canonicalTag(url: string) {
  const u = new URL(url);
  return `<link rel="canonical" href="${attr(u.href)}">`;
}

export function hreflangTags(entries: { lang: string; url: string }[], xDefault?: string): string {
  const re = /^(x-default|[a-z]{2,3}(-[A-Za-z]{4})?(-[A-Za-z]{2}|-\d{3})?)$/;
  const lines = entries.map((e) => {
    if (!re.test(e.lang)) throw new Error(`Invalid language code: ${e.lang}`);
    return `<link rel="alternate" hreflang="${attr(e.lang)}" href="${attr(new URL(e.url).href)}">`;
  });
  if (xDefault) lines.push(`<link rel="alternate" hreflang="x-default" href="${attr(new URL(xDefault).href)}">`);
  return lines.join("\n");
}

export interface RedirectRule { from: string; to: string; status?: 301 | 302 | 307 | 308 }

export function htaccessRedirects(rules: RedirectRule[], opts: { forceHttps?: boolean; wwwMode?: "add" | "remove" | "none" } = {}): string {
  const out: string[] = ["# Generated by Rankacorn - review before deploying; test on staging first.", "# Requires Apache with mod_alias / mod_rewrite."];
  const needsRewrite = opts.forceHttps || (opts.wwwMode && opts.wwwMode !== "none");
  if (needsRewrite) {
    out.push("<IfModule mod_rewrite.c>", "RewriteEngine On");
    if (opts.forceHttps) out.push("RewriteCond %{HTTPS} off", "RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]");
    if (opts.wwwMode === "add") out.push("RewriteCond %{HTTP_HOST} !^www\\. [NC]", "RewriteRule ^ https://www.%{HTTP_HOST}%{REQUEST_URI} [L,R=301]");
    if (opts.wwwMode === "remove") out.push("RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]", "RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]");
    out.push("</IfModule>");
  }
  for (const r of rules) {
    if (/[\s"]/.test(r.from) || !r.from.startsWith("/")) throw new Error(`Source path must start with "/" and contain no spaces: ${r.from}`);
    if (/\s|"/.test(r.to)) throw new Error(`Destination must not contain spaces or quotes: ${r.to}`);
    out.push(`Redirect ${r.status ?? 301} ${r.from} ${r.to}`);
  }
  return out.join("\n") + "\n";
}

export function webManifest(o: { name: string; shortName?: string; startUrl?: string; display?: "standalone" | "browser" | "minimal-ui" | "fullscreen"; themeColor?: string; backgroundColor?: string; icons?: { src: string; sizes: string; type?: string }[] }) {
  const color = /^#[0-9a-f]{3,8}$/i;
  if (o.themeColor && !color.test(o.themeColor)) throw new Error("themeColor must be a hex color.");
  if (o.backgroundColor && !color.test(o.backgroundColor)) throw new Error("backgroundColor must be a hex color.");
  return JSON.stringify({
    name: o.name, short_name: o.shortName ?? o.name.slice(0, 12), start_url: o.startUrl ?? "/", display: o.display ?? "standalone",
    theme_color: o.themeColor ?? "#0b1b3b", background_color: o.backgroundColor ?? "#ffffff", icons: o.icons ?? [],
  }, null, 2) + "\n";
}

export type SchemaType = "Article" | "FAQPage" | "Organization" | "LocalBusiness" | "Product" | "BreadcrumbList";

export function schemaMarkup(type: SchemaType, d: Record<string, unknown>): string {
  const req = (k: string) => { if (d[k] === undefined || d[k] === "") throw new Error(`Missing required field: ${k}`); return d[k]; };
  let obj: Record<string, unknown> = { "@context": "https://schema.org", "@type": type };
  switch (type) {
    case "Article":
      obj = { ...obj, headline: req("headline"), datePublished: d.datePublished, dateModified: d.dateModified, author: d.author ? { "@type": "Person", name: d.author } : undefined, image: d.image, description: d.description };
      break;
    case "FAQPage": {
      const faqs = req("faqs") as { question: string; answer: string }[];
      obj = { ...obj, mainEntity: faqs.map((f) => ({ "@type": "Question", name: f.question, acceptedAnswer: { "@type": "Answer", text: f.answer } })) };
      break;
    }
    case "Organization":
      obj = { ...obj, name: req("name"), url: d.url, logo: d.logo, sameAs: d.sameAs };
      break;
    case "LocalBusiness":
      obj = { ...obj, name: req("name"), url: d.url, telephone: d.telephone, address: d.address ? { "@type": "PostalAddress", ...(d.address as object) } : undefined, openingHours: d.openingHours };
      break;
    case "Product":
      obj = { ...obj, name: req("name"), image: d.image, description: d.description, sku: d.sku, offers: d.price !== undefined ? { "@type": "Offer", price: d.price, priceCurrency: d.currency ?? "USD", availability: "https://schema.org/InStock", url: d.url } : undefined };
      break;
    case "BreadcrumbList": {
      const items = req("items") as { name: string; url: string }[];
      obj = { ...obj, itemListElement: items.map((it, i) => ({ "@type": "ListItem", position: i + 1, name: it.name, item: it.url })) };
      break;
    }
  }
  return `<script type="application/ld+json">\n${safeJson(obj)}\n</script>`;
}

export function formatJsonLd(raw: string): { ok: true; formatted: string; types: string[]; warnings: string[] } | { ok: false; error: string } {
  let parsed: unknown;
  try { parsed = JSON.parse(raw); } catch (e) { return { ok: false, error: (e as Error).message }; }
  const nodes = Array.isArray(parsed) ? parsed : [parsed];
  const types: string[] = [];
  const warnings: string[] = [];
  for (const n of nodes as Record<string, unknown>[]) {
    if (!n || typeof n !== "object") { warnings.push("Entry is not an object."); continue; }
    if (!n["@context"]) warnings.push('Missing "@context" (usually "https://schema.org").');
    const t = n["@type"];
    if (!t) warnings.push('Missing "@type".'); else types.push(...(Array.isArray(t) ? t.map(String) : [String(t)]));
  }
  return { ok: true, formatted: JSON.stringify(parsed, null, 2), types, warnings };
}

export function analyzeUrlParams(input: string) {
  const u = new URL(input);
  const tracking = /^(utm_|fbclid|gclid|msclkid|mc_cid|mc_eid|_ga|ref$)/i;
  const params = [...u.searchParams.entries()].map(([key, value]) => ({ key, value, isTracking: tracking.test(key) }));
  return { origin: u.origin, path: u.pathname, hash: u.hash, params, hasTrackingParams: params.some((p) => p.isTracking) };
}

export function urlEncodeDecode(input: string, mode: "encode" | "decode"): string {
  return mode === "encode" ? encodeURIComponent(input) : decodeURIComponent(input);
}

export function serpSnippet(title: string, description: string, url: string) {
  const u = new URL(url);
  const cut = (s: string, n: number) => (s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s);
  return {
    displayUrl: u.hostname + (u.pathname === "/" ? "" : u.pathname.split("/").filter(Boolean).join(" › ").replace(/^/, " › ")),
    title: cut(title, 60),
    description: cut(description, 160),
    titleTruncated: title.length > 60,
    descriptionTruncated: description.length > 160,
    note: "Approximation using character counts; Google truncates by pixel width and may rewrite snippets.",
  };
}

// ---------- UTM campaign builder

export interface UtmOptions {
  url: string;
  source: string;
  medium: string;
  campaign: string;
  term?: string;
  content?: string;
  id?: string;
}

/** Normalise a UTM value the way analytics tools expect: lowercase, underscores. */
export const utmValue = (s: string) => s.trim().toLowerCase().replace(/\s+/g, "_");

export function utmUrl(o: UtmOptions) {
  const u = new URL(/^https?:\/\//i.test(o.url) ? o.url : `https://${o.url.trim()}`);
  const params: [string, string][] = [];
  const warnings: string[] = [];
  const put = (key: string, value?: string) => {
    if (!value || !value.trim()) return;
    const v = utmValue(value);
    u.searchParams.set(key, v);
    params.push([key, v]);
  };
  put("utm_source", o.source);
  put("utm_medium", o.medium);
  put("utm_campaign", o.campaign);
  put("utm_term", o.term);
  put("utm_content", o.content);
  put("utm_id", o.id);

  if (!o.source?.trim()) warnings.push("Add utm_source: without it most reports group the traffic as direct or referral.");
  if (!o.medium?.trim()) warnings.push("Add utm_medium (for example cpc, email, social) so channels stay separate.");
  if (!o.campaign?.trim()) warnings.push("Add utm_campaign so the activity can be reported on later.");
  if ([...u.searchParams.keys()].filter((k) => /^utm_/i.test(k)).length > 5) warnings.push("Many UTM values: some analytics tools truncate very long URLs.");
  return { url: u.href, params, warnings };
}

// ---------- Meta / social tag generation

export interface MetaOptions {
  title?: string;
  description?: string;
  url?: string;
  image?: string;
  type?: string;
  siteName?: string;
  twitterHandle?: string;
  card?: string;
  robots?: string;
  author?: string;
}

const absOrEmpty = (v: string | undefined, base: string | undefined): string => {
  if (!v?.trim()) return "";
  try { return new URL(v.trim(), base && /^https?:\/\//i.test(base) ? base : "https://example.com").href; } catch { return ""; }
};

/** Build a complete, escaped <head> metadata block. */
export function metaTags(o: MetaOptions): string {
  const lines: string[] = [];
  if (o.title?.trim()) lines.push(`<title>${attr(o.title.trim())}</title>`);
  if (o.description?.trim()) lines.push(`<meta name="description" content="${attr(o.description.trim())}">`);
  lines.push(`<meta name="robots" content="${attr(o.robots?.trim() || "index,follow")}">`);
  if (o.author?.trim()) lines.push(`<meta name="author" content="${attr(o.author.trim())}">`);
  lines.push(`<meta name="viewport" content="width=device-width, initial-scale=1">`);

  const canonical = absOrEmpty(o.url, o.url);
  if (canonical) lines.push(`<link rel="canonical" href="${attr(canonical)}">`);

  const title = o.title?.trim() || "";
  const desc = o.description?.trim() || "";
  const image = absOrEmpty(o.image, canonical || o.url);
  const url = canonical || (o.url?.trim() ?? "");

  const og: [string, string][] = [
    ["og:type", o.type?.trim() || "website"],
    ["og:title", title],
    ["og:description", desc],
    ["og:url", url],
    ["og:image", image],
    ["og:site_name", o.siteName?.trim() || ""],
  ];
  for (const [p, v] of og) if (v) lines.push(`<meta property="${p}" content="${attr(v)}">`);

  const card = o.card?.trim() || (image ? "summary_large_image" : "summary");
  const tw: [string, string][] = [
    ["twitter:card", card],
    ["twitter:title", title],
    ["twitter:description", desc],
    ["twitter:image", image],
    ["twitter:site", o.twitterHandle?.trim().startsWith("@") ? o.twitterHandle.trim() : o.twitterHandle?.trim() ? `@${o.twitterHandle.trim()}` : ""],
  ];
  for (const [n, v] of tw) if (v) lines.push(`<meta name="${n}" content="${attr(v)}">`);

  return lines.join("\n");
}

/** The recommended tags for one page, given what it already declares. */
export function socialPreviewTags(input: { title?: string | null; description?: string | null; url: string; image?: string | null; siteName?: string; card?: string }): string {
  return metaTags({
    title: input.title ?? undefined,
    description: input.description ?? undefined,
    url: input.url,
    image: input.image ?? undefined,
    siteName: input.siteName,
    card: input.card,
  });
}
